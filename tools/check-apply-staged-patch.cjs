const fs = require('fs');
const os = require('os');
const path = require('path');
const assert = require('assert/strict');
const Planner = require('./staged-patch.cjs');
const Apply = require('./apply-staged-patch.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jx-stage-'));
const file = path.join(root, 'skills.txt');
fs.writeFileSync(file, Buffer.from('a\tb\r\n1\told\r\n', 'latin1'));
const source = fs.readFileSync(file);
const after = Buffer.from('a\tb\r\n1\tnew\r\n', 'latin1');
const manifest = { schema: Planner.SCHEMA, mode: 'stage-only', blocked: [], operations: [{ path: 'skills.txt', precondition: { sha256: Planner.sha256(source) }, result: { bytes: after.length, sha256: Planner.sha256(after) }, edits: [{ start: 7, end: 10, before: 'old', after: 'new' }] }] };
const passed = [];
const dry = Apply.applyManifest({ manifest, root, dryRun: true });
assert.equal(dry.mode, 'dry-run'); assert.deepEqual(fs.readFileSync(file), source); passed.push('dry-run never writes');
const backupDir = path.join(root, 'backup');
const applied = Apply.applyManifest({ manifest, root, backupDir, allowWrites: true, dryRun: false });
assert.equal(applied.mode, 'applied'); assert.deepEqual(fs.readFileSync(file), after); assert.equal(fs.readdirSync(backupDir).length, 2); passed.push('backup, atomic write and read-back hash pass');
fs.writeFileSync(file, source);
assert.throws(() => Apply.applyManifest({ manifest: { ...manifest, operations: [{ ...manifest.operations[0], precondition: { sha256: Planner.sha256(Buffer.from('stale')) } }] }, root, backupDir, allowWrites: true, dryRun: false }), /Precondition hash changed/); passed.push('stale precondition is rejected');
console.log(JSON.stringify({ checkedAt: new Date().toISOString(), passed: passed.length, checks: passed, writesToGame: false, output: 'evidence/apply-staged-patch-checks.json' }, null, 2));
